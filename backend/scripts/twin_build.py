"""India Twin build CLI: check manual downloads, build the backbone and datasets, sync to Postgres."""
from __future__ import annotations

import argparse
import json
import os
import sys
from dataclasses import asdict
from pathlib import Path

_BACKEND = Path(__file__).resolve().parent.parent
if str(_BACKEND) not in sys.path:  # allow `python scripts/twin_build.py`
    sys.path.insert(0, str(_BACKEND))

from twin.paths import TwinPaths  # noqa: E402

_LOGIN = "Needs a browser session (login or captcha), so it cannot be scripted."

# relative path (glob under data/twin/manual/) -> download instructions. Single source
# for both `check` and the generated data/twin/manual/README.md.
EXPECTED_MANUAL_FILES: dict[str, str] = {
    "lgd/states.csv": (
        "Local Government Directory, https://lgdirectory.gov.in/ -> Download Directory -> "
        "States. Export as CSV. " + _LOGIN
    ),
    "lgd/districts.csv": (
        "Local Government Directory, https://lgdirectory.gov.in/ -> Download Directory -> "
        "Districts (with Census 2011 code). Export as CSV. " + _LOGIN
    ),
    "soi/district_boundaries.*": (
        "Survey of India administrative district boundaries, "
        "https://onlinemaps.surveyofindia.gov.in/ (.shp, .geojson or .gpkg). " + _LOGIN
    ),
    "soi/india_outline.*": (
        "Survey of India India outline (national boundary), "
        "https://onlinemaps.surveyofindia.gov.in/ (.shp, .geojson or .gpkg). " + _LOGIN
    ),
    "census2011/district_boundaries.*": (
        "Census 2011 district boundaries from DataMeet, https://github.com/datameet/maps "
        "(.shp, .geojson or .gpkg). Plain download, no login. Used only for the crosswalk, never drawn."
    ),
    "census2011/pca_district*.csv": (
        "Census 2011 Primary Census Abstract, district level, https://censusindia.gov.in/ "
        "(or data.gov.in mirror), saved as CSV."
    ),
    "viirs/VNL_*average_masked*.tif": (
        "VIIRS annual nighttime lights, average_masked GeoTIFF for one year, "
        "https://eogdata.mines.edu/products/vnl/. Free registration and login required in a browser."
    ),
}

_EXTS = (".shp", ".geojson", ".gpkg")


def _find(manual: Path, pattern: str) -> Path | None:
    """First (sorted) match; patterns ending in `.*` accept only boundary file extensions."""
    hits = sorted(manual.glob(pattern))
    if pattern.endswith(".*"):
        hits = [h for h in hits if h.suffix.lower() in _EXTS]
    return hits[0] if hits else None


def render_manual_readme() -> str:
    lines = [
        "# Manual data downloads",
        "",
        "Some sources need a browser login or a captcha, so they are downloaded by hand and placed",
        "here. Files in this folder are git-ignored (except this README). Check progress with",
        "`python scripts/twin_build.py check` from `backend/`, then build with",
        "`python scripts/twin_build.py build --boundary-version lgd-YYYYMMDD`.",
        "",
        "Expected files, relative to `data/twin/manual/`:",
        "",
    ]
    for rel, how in EXPECTED_MANUAL_FILES.items():
        lines += [f"## `{rel}`", "", how, ""]
    lines += [
        "The place-name alias list lives in `data/twin/seed/aliases.csv` (committed).",
        "",
        "This file is generated by `render_manual_readme()` in `backend/scripts/twin_build.py`.",
    ]
    return "\n".join(lines) + "\n"


def _check(paths: TwinPaths) -> int:
    missing = 0
    for rel in EXPECTED_MANUAL_FILES:
        found = _find(paths.manual, rel)
        if found is None:
            missing += 1
        print(f"{'✓' if found else '✗'} {rel}")
    return 1 if missing else 0


def _emit(obj) -> None:
    print(json.dumps(asdict(obj), default=str))


def _build(paths: TwinPaths, boundary_version: str) -> int:
    from app.data_registry import SOURCE_REGISTRY
    from twin.pipeline.base import run_pipeline
    from twin.pipeline.census2011 import Census2011Adapter
    from twin.pipeline.viirs import ViirsAdapter
    from twin.places.build import BackboneInputs, build_backbone, load_backbone

    found = {rel: _find(paths.manual, rel) for rel in EXPECTED_MANUAL_FILES}
    absent = [rel for rel, f in found.items() if f is None]
    if absent:
        print(f"build failed: missing manual files: {', '.join(absent)}", file=sys.stderr)
        return 1
    aliases = paths.seed / "aliases.csv"
    if not aliases.exists():
        print(f"build failed: missing {aliases}", file=sys.stderr)
        return 1

    inputs = BackboneInputs(
        lgd_states=found["lgd/states.csv"],
        lgd_districts=found["lgd/districts.csv"],
        soi_districts=found["soi/district_boundaries.*"],
        soi_outline=found["soi/india_outline.*"],
        census2011_districts=found["census2011/district_boundaries.*"],
        aliases=aliases,
    )
    report = build_backbone(inputs, paths, boundary_version)
    _emit(report)
    if report.unmatched_boundaries:
        print(f"build failed: unmatched boundaries: {report.unmatched_boundaries}", file=sys.stderr)
        return 1
    if report.districts_without_boundary > 0:
        print(f"build failed: {report.districts_without_boundary} districts have no boundary", file=sys.stderr)
        return 1

    ctx = load_backbone(paths, known_sources={s.id for s in SOURCE_REGISTRY})
    status = 0
    for adapter in (Census2011Adapter(), ViirsAdapter()):
        result = run_pipeline(adapter, ctx)
        _emit(result)
        if not result.report.ok:
            print(f"build failed: {adapter.source_id} validation: {result.report.problems}", file=sys.stderr)
            status = 1
    return status


def _sync(paths: TwinPaths, dsn: str | None) -> int:
    from twin.store.pg_sync import sync_to_postgres

    dsn = dsn or os.environ.get("TWIN_PG_DSN", "")
    if not dsn:
        print("postgres sync skipped", file=sys.stderr)
        return 0
    print(json.dumps(sync_to_postgres(paths, dsn)))
    return 0


def main(argv: list[str], paths: TwinPaths | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):  # cp1252 consoles cannot encode the check glyphs
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    parser = argparse.ArgumentParser(prog="twin_build")
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("check", help="list expected manual files")
    b = sub.add_parser("build", help="build backbone and datasets")
    b.add_argument("--boundary-version", required=True)
    s = sub.add_parser("sync", help="upsert into Postgres")
    s.add_argument("--dsn", default=None)
    args = parser.parse_args(argv)
    paths = paths or TwinPaths.default()
    if args.cmd == "check":
        return _check(paths)
    if args.cmd == "build":
        return _build(paths, args.boundary_version)
    return _sync(paths, args.dsn)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
